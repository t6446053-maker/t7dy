  static List<QuestionModel> getQuestionsForCategory(String categoryTitle) {
    final items = _bank[categoryTitle];
    if (items == null || items.isEmpty) return [];

    return items
        .map(
          (q) => QuestionModel(
            id: '${categoryTitle}_${q.team}_${q.points}',
            category: categoryTitle,
            points: q.points,
            ownerTeam: q.team,
            questionText: q.q,
            options: q.options,
            correctOptionIndex: q.correct,
            imageQuery: q.img,
          ),
        )
        .toList();
  }
